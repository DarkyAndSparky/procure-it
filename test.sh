#!/bin/bash
# Прогон автотестов. Отдельно от start.sh/install.sh намеренно — тесты не
# нужны в прод-окружении (Docker-образ их и не копирует, см. Dockerfile и
# .dockerignore), это чисто dev-инструмент.
set -e

cd "$(dirname "$0")"

echo ""
echo "══════════════════════════════════════════"
echo "  procure-it — Тесты"
echo "══════════════════════════════════════════"
echo ""

# Проверка версии Node.js, установка зависимостей (и их актуальности) —
# та же логика, что и для запуска сервера, переиспользуем install.sh
# вместо третьей копии одних и тех же проверок (--from-start подавляет его
# собственный баннер/финальную подсказку "для запуска сервера").
./install.sh --from-start

npm test
